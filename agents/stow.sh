#!/usr/bin/env bash
# Stow per-agent config packages into each agent's home directory.
#
# Usage: ./stow.sh [-D|-R] [claude|opencode|codex|kiro ...]
#   -D  unstow    -R  restow (default: stow)
#   No agent names means all agents.
set -euo pipefail
shopt -s extglob

AGENTS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RULES_DIR="$AGENTS_DIR/shared/rules"
ALL_AGENTS=(claude opencode codex kiro)

target_for() {
  case "$1" in
    claude) echo "$HOME/.claude" ;;
    opencode) echo "$HOME/.config/opencode" ;;
    codex) echo "$HOME/.codex" ;;
    kiro) echo "$HOME/.kiro" ;;
    *)
      echo "unknown agent: $1 (expected: ${ALL_AGENTS[*]})" >&2
      return 1
      ;;
  esac
}

# Codex and OpenCode don't expand `@file` imports, so inline the shared rules.
render_agents_md() {
  local template="$1" output="$2" line rule
  {
    echo "<!-- Generated by agents/stow.sh from $(basename "$template"). Do not edit. -->"
    echo
    while IFS= read -r line || [[ -n "$line" ]]; do
      if [[ "$line" =~ ^@(.+\.md)$ ]]; then
        rule="$RULES_DIR/${BASH_REMATCH[1]}"
        [[ -f "$rule" ]] || { echo "missing rule: $rule" >&2; return 1; }
        cat "$rule"
      else
        echo "$line"
      fi
    done <"$template"
  } >"$output"
}

# Links left behind by older layouts (e.g. agents/go.md) block stow with conflicts.
remove_dangling_agent_links() {
  local target="$1" link
  [[ -d "$target" ]] || return 0
  while IFS= read -r -d '' link; do
    if [[ ! -e "$link" && "$(readlink "$link")" == *@(agents|dotfiles)/* ]]; then
      echo "  removing stale link $link -> $(readlink "$link")"
      rm "$link"
    fi
  done < <(find "$target" -maxdepth 2 -type l -print0)
}

stow_agent() {
  local action="$1" agent="$2" target template
  target="$(target_for "$agent")"
  template="$AGENTS_DIR/$agent/AGENTS.template.md"

  echo "$agent -> $target"
  if [[ "$action" != "-D" ]]; then
    mkdir -p "$target"
    remove_dangling_agent_links "$target"
    [[ -f "$template" ]] && render_agents_md "$template" "$AGENTS_DIR/$agent/AGENTS.md"
  fi

  # --no-folding keeps target dirs (skills/, steering/) real, so files the
  # agent writes there never end up inside this repo.
  stow --dir="$AGENTS_DIR" --target="$target" --no-folding \
    --ignore='\.template\.md$' "$action" "$agent"
}

main() {
  local action="-S"
  if [[ "${1:-}" == -[DRS] ]]; then
    action="$1"
    shift
  fi

  local agents=("$@")
  ((${#agents[@]})) || agents=("${ALL_AGENTS[@]}")

  local agent
  for agent in "${agents[@]}"; do
    target_for "$agent" >/dev/null
  done
  for agent in "${agents[@]}"; do
    stow_agent "$action" "$agent"
  done
}

main "$@"
